def unify(a, b, sub):
    if a == b:
        return True

    if a.islower():
        sub[a] = b
        return True

    if b.islower():
        sub[b] = a
        return True

    return False


A = ["x", "Apple"]
B = ["Riya", "y"]

sub = {}

if len(A) == len(B):
    result = all(unify(a, b, sub) for a, b in zip(A, B))
else:
    result = False

if result:
    print("Unification Successful!")
    print("Substitution:", sub)

    A = [sub.get(x, x) for x in A]
    B = [sub.get(x, x) for x in B]

    print("Expression A: Eats(" + ", ".join(A) + ")")
    print("Expression B: Eats(" + ", ".join(B) + ")")
else:
    print("Unification Failed!")


