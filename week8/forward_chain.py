facts = {
    ("American", "Robert"),
    ("Enemy", "A", "America"),
    ("Owns", "A", "T1"),
    ("Missile", "T1")
}

rules = [
    ([("Missile", "?x")],
     ("Weapon", "?x")),

    ([("Enemy", "?x", "America")],
     ("Hostile", "?x")),

    ([("Missile", "?x"), ("Owns", "A", "?x")],
     ("Sells", "Robert", "?x", "A")),

    ([("American", "?p"), ("Weapon", "?q"),
      ("Sells", "?p", "?q", "?r"), ("Hostile", "?r")],
     ("Criminal", "?p"))
]


def match(pattern, fact, substitution):
    if pattern[0] != fact[0]:
        return None

    sub = substitution.copy()

    if len(pattern) != len(fact):
        return None

    for p, f in zip(pattern[1:], fact[1:]):
        if p.startswith("?"):
            if p in sub and sub[p] != f:
                return None
            sub[p] = f
        elif p != f:
            return None

    return sub


def forward_chaining(facts, rules):
    facts = set(facts)

    while True:
        new_facts = set()

        for conditions, conclusion in rules:
            substitutions = [{}]

            for condition in conditions:
                updated = []

                for sub in substitutions:
                    for fact in facts:
                        result = match(
                            tuple(sub.get(x, x) for x in condition),
                            fact, sub
                        )
                        if result is not None:
                            updated.append(result)

                substitutions = updated

            for sub in substitutions:
                new_fact = tuple(sub.get(x, x) for x in conclusion)

                if new_fact not in facts:
                    new_facts.add(new_fact)

        if not new_facts:
            break

        facts.update(new_facts)

        for fact in new_facts:
            print("New fact:", fact)

    return facts


print("Forward Chaining Started\n")

result = forward_chaining(facts, rules)

query = ("Criminal", "Robert")

print("\nQuery:", query)

if query in result:
    print("Result: YES, Robert is a criminal.")
else:
    print("Result: NO, Robert is not proved criminal.")


